"""Turn fourmation/data/x_strategy_book.json into windows/book_data.h.

Only the first player's (X) proven winning moves are needed at play time. Each
entry is stored in all 8 board symmetries, so the C side looks positions up
directly (binary search on (X cubes, O cubes, last move)) without canonicalising.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))

from fourmation import native as nv  # noqa: E402
from fourmation.rules import TRANSFORMS, State, parse_coord, transform_state  # noqa: E402


def main(out=os.path.join(HERE, "book_data.h")):
    book = json.load(open(os.path.join(HERE, "..", "fourmation", "data", "x_strategy_book.json")))
    rows = {}
    for key, e in book.items():
        if e.get("result") != "WIN" or not e.get("best"):
            continue
        st = State.from_compact(key)
        if st.to_move != 1:
            continue
        best = parse_coord(e["best"])
        for k in range(8):
            t = transform_state(st, k)
            b0, b1, last, side = nv.encode(t.board, t.last, t.to_move)
            mv = nv.sq(TRANSFORMS[k][best])
            last = 64 if last < 0 else last
            prev = rows.get((b0, b1, last))
            if prev is not None and prev != mv:
                # a symmetric position maps the move to an equivalent square; keep the first
                continue
            rows[(b0, b1, last)] = mv
    items = sorted(rows.items())
    with open(out, "w") as f:
        f.write("/* generated by windows/gen_book.py from fourmation/data/x_strategy_book.json */\n")
        f.write("/* first player's proven winning moves, all 8 symmetries; sorted by (b0, b1, last) */\n")
        f.write("typedef struct { unsigned long long b0, b1; unsigned char last, move; } BookEntry;\n")
        f.write(f"#define BOOK_N {len(items)}\n")
        f.write("static const BookEntry BOOK[BOOK_N] = {\n")
        for (b0, b1, last), mv in items:
            f.write(f"{{0x{b0:x}ULL,0x{b1:x}ULL,{last},{mv}}},\n")
        f.write("};\n")
    print(f"{len(items)} entries -> {out}")


if __name__ == "__main__":
    main()
